"""
==========================================================
LANGGRAPH: LIVE WEB SEARCH WITH DUCKDUCKGO & CHATGROQ
==========================================================
Demonstrates:
1. Adding a free external search engine (DuckDuckGo) as a tool
2. Binding DuckDuckGo alongside custom Python tools
3. Automatic routing and execution via ToolNode and tools_condition
==========================================================
"""

import os
from typing import Annotated, Sequence
from dotenv import load_dotenv

from langchain_community.tools import DuckDuckGoSearchRun
from langchain_core.messages import BaseMessage, HumanMessage
from langchain_core.tools import tool
from langchain_groq import ChatGroq
from langgraph.graph import END, START, StateGraph
from langgraph.graph.message import add_messages
from langgraph.prebuilt import ToolNode, tools_condition
from typing_extensions import TypedDict

load_dotenv()


# ==========================================================
# 1. TOOL DEFINITIONS
# ==========================================================
# A. Free Live Web Search Tool
# DuckDuckGoSearchRun requires no API key and executes live HTTP requests
web_search = DuckDuckGoSearchRun()


# B. Local Python Tool
@tool
def calculate(expression: str) -> str:
    """Evaluate a standard mathematical expression string, such as '15 * 8' or '240 / 6'."""
    try:
        allowed_chars = set("0123456789+-*/(). ")
        if not all(c in allowed_chars for c in expression):
            return "Error: Unsupported characters in mathematical expression."
        return str(eval(expression, {"__builtins__": None}, {}))
    except Exception as e:
        return f"Calculation failed: {str(e)}"


# Bundle both local and external tools together
tools = [web_search, calculate]


# ==========================================================
# 2. MODEL INITIALIZATION & BINDING
# ==========================================================
llm = ChatGroq(
    model="openai/gpt-oss-20b",
    temperature=0.0,
)

# Bind the tool schemas directly to the LLM
llm_with_tools = llm.bind_tools(tools)


# ==========================================================
# 3. STATE DEFINITION
# ==========================================================
class AgentState(TypedDict):
    messages: Annotated[Sequence[BaseMessage], add_messages]


# ==========================================================
# 4. NODES
# ==========================================================
def chatbot(state: AgentState) -> dict:
    """Invokes the model with current message history."""
    response = llm_with_tools.invoke(state["messages"])
    return {"messages": [response]}


# ToolNode handles invocation for any tool in the list, including DuckDuckGo
tool_node = ToolNode(tools)


# ==========================================================
# 5. GRAPH CONSTRUCTION
# ==========================================================
workflow = StateGraph(AgentState)

workflow.add_node("chatbot", chatbot)
workflow.add_node("tools", tool_node)

# START -> chatbot
workflow.add_edge(START, "chatbot")

# Conditional routing from chatbot:
# - If model requested tool -> "tools"
# - If model generated final text -> END
workflow.add_conditional_edges(
    "chatbot",
    tools_condition,
    {"tools": "tools", END: END},
)

# Return tool output back to chatbot to formulate the final answer
workflow.add_edge("tools", "chatbot")

graph = workflow.compile()


# ==========================================================
# 6. VERIFICATION RUN
# ==========================================================
def run_query(query: str):
    print("\n" + "=" * 60)
    print(f"USER: {query}")
    print("=" * 60)

    result = graph.invoke(
        {"messages": [HumanMessage(content=query)]}
    )

    for msg in result["messages"]:
        role = msg.__class__.__name__
        print(f"\n[{role}]")

        # Display tool call details if generated by the LLM
        if hasattr(msg, "tool_calls") and msg.tool_calls:
            print(f"Tool Requested: {msg.tool_calls}")

        # Display message content (truncated for large search payloads)
        if msg.content:
            content = msg.content
            if role == "ToolMessage" and len(content) > 300:
                content = content[:300] + "... [TRUNCATED SEARCH RESULTS]"
            print(content)


if __name__ == "__main__":
    # Test 1: Live web query triggering DuckDuckGo
    run_query("What is the latest score or status of the most recent Formula 1 race?")

    # Test 2: Local calculation (bypasses search)
    run_query("Compute 945 divided by 15.")