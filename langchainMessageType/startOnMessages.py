"""
====================================================
LANGCHAIN MESSAGE OBJECTS
====================================================

WHAT THIS PROGRAM TEACHES

1. HumanMessage
2. AIMessage
3. SystemMessage
4. Chat History
5. Message Lists
6. Why LangGraph stores messages

IMPORTANT:

LangGraph does NOT directly work with
plain strings most of the time.

Instead, conversations are stored as
message objects.

Example:

User -> HumanMessage
AI   -> AIMessage
Rules -> SystemMessage

These messages are stored inside a list
called chat history.

Later in LangGraph this chat history is
usually stored inside State.

====================================================
"""

# ==================================================
# IMPORT MESSAGE TYPES
# ==================================================

from langchain_core.messages import (
    HumanMessage,
    AIMessage,
    SystemMessage
)

# ==================================================
# SYSTEM MESSAGE
# ==================================================
#
# ROLE:
# Gives instructions to the AI.
#
# Think:
# "Who are you?"
# "How should you behave?"
#
# Not written by the user.
#
# Usually appears at the beginning.
#
# Example:
# You are a helpful assistant.
# You are a coding tutor.
# Explain simply.
#

system_message = SystemMessage(
    content="""
You are a helpful AI tutor.
Explain concepts simply.
Focus on GenAI Engineering topics.
"""
)

# ==================================================
# HUMAN MESSAGE
# ==================================================
#
# Represents user input.
#
# User ---> AI
#
# In a chatbot every question becomes
# a HumanMessage.
#

human_message = HumanMessage(
    content="How can I become a GenAI Engineer?",
    name="Hari"
)

# ==================================================
# AI MESSAGE
# ==================================================
#
# Represents model output.
#
# AI ---> User
#
# Every response generated by the model
# becomes an AIMessage.
#

ai_message = AIMessage(
    content="""
Learn:
1. Python
2. LangChain
3. LangGraph
4. Vector Databases
5. RAG
6. Prompt Engineering
""",
    name="TutorBot"
)

# ==================================================
# CHAT HISTORY
# ==================================================
#
# Messages are stored in order.
#
# This list represents an entire conversation.
#
# Earlier messages provide context for
# future responses.
#

messages = [
    system_message,
    human_message,
    ai_message
]

# ==================================================
# NEW USER MESSAGE
# ==================================================

messages.append(
    HumanMessage(
        content="Should I learn message objects before LangGraph?"
    )
)

# ==================================================
# AI RESPONSE
# ==================================================

messages.append(
    AIMessage(
        content="""
Yes.

You only need the basics because
LangGraph stores conversations
using message objects.
"""
    )
)

# ==================================================
# DISPLAY CHAT HISTORY
# ==================================================

print("\n===== CHAT HISTORY =====\n")

for message in messages:

    print(f"TYPE    : {message.__class__.__name__}")
    print(f"CONTENT : {message.content}")
    print("-" * 60)


# ==================================================
# EXTRA LEARNING
# ==================================================
#
# message.content
# returns actual text
#
# message.__class__.__name__
# returns object type
#
# Examples:
#
# HumanMessage
# AIMessage
# SystemMessage
#
# ==================================================


# What to Understand Here
# Python
# AIMessage(...)
# AIMessage → Class
# (...) → Constructor call
# content= → Named parameter
# name= → Optional named parameter

# Same idea:

# Python
# person = Person(name="Hari")
# car = Car(color="Red")
# message = HumanMessage(content="Hello")